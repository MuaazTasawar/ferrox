//! `license-checker` -- a deliberately small demo app that exercises every
//! Ferrox Layer 1/3 primitive built so far, end to end, the way a real
//! consuming crate would:
//!
//! - Layer 1 (`enc!`): the valid license key and both outcome messages are
//!   compile-time encrypted, and -- because `build.rs` wires in
//!   `ferrox-keygen` -- all three share one per-build key (F1.8, closed as
//!   of this phase; see docs/THREAT_MODEL.md).
//! - Layer 3 (`ferrox-runtime`): `init()` installs the silent release-mode
//!   panic hook and starts the checksum thread; three independent
//!   anti-debug checks are called from three different, unrelated points
//!   in `main` (F1.7 -- deliberately not bundled into one call); and the
//!   license verdict is flipped to "invalid" if `tamper_detected()` reads
//!   true right before the verdict is produced (F1.5's silent-corruption
//!   behavior, concretely implemented here -- `ferrox-runtime` itself has
//!   no opinion on what "corrupt the output" means for this crate).
//!
//! Usage: `license-checker <key>` -- pass the correct key (see below) to
//! see the "valid" path, anything else for "invalid". The key itself is
//! never visible via `strings <binary>` (verified in CI, see
//! `.github/workflows/ci.yml`) -- you have to read this source file, or
//! run the program with an empty/wrong key and only see the generic
//! rejection message.

use ferrox_macros::enc;
use ferrox_runtime::{anti_debug, tamper_detected};

// keys.rs -- generated by ferrox-keygen's run() in build.rs. FERROX_BUILD_SEED
// and FERROX_STRING_KEY are included for completeness/future use; this crate's
// enc!() calls actually receive their shared key via the FERROX_STRING_KEY_HEX
// env var (see ferrox-macros' enc_macro.rs), not by reading these constants
// directly -- both ultimately derive from the same per-build FerroxKeys, so
// they agree. FERROX_CHECKSUM_SALT is generated but not yet consumed (see
// ferrox-keygen's module docs) -- `#[allow(dead_code)]` on all three in the
// generated file keeps this crate's build warning-free despite that.
include!(concat!(env!("OUT_DIR"), "/keys.rs"));

/// The one valid license key this demo accepts. This literal exists only
/// here, in source -- `enc!` ensures it is never present as plaintext in
/// the compiled binary (F1.2).
fn valid_license_key() -> &'static str {
    enc!("FERROX-DEMO-1234-5678")
}

fn valid_message() -> &'static str {
    enc!("License valid -- thank you for a legitimate purchase.")
}

fn invalid_message() -> &'static str {
    enc!("Invalid license key.")
}

fn check_license(input: &str) -> bool {
    input == valid_license_key()
}

fn main() {
    // Layer 3 setup: silent panic hook (release builds only) + checksum
    // thread baseline. Call site 1 of "scattered calls" in spirit (F1.7
    // is about anti-debug specifically, but the same philosophy applies
    // to when/where Layer 3 machinery gets invoked generally).
    ferrox_runtime::init();

    // Anti-debug check 1 of 3: timing anomaly. Runs on both platforms,
    // placed here -- before any license logic even starts -- rather than
    // bundled with the other two checks below (F1.7).
    anti_debug::timing::check();

    let args: Vec<String> = std::env::args().collect();
    let provided_key = args.get(1).map(String::as_str).unwrap_or("");

    // Anti-debug check 2 of 3: platform-specific self-trace / debugger-flag
    // check, placed at a second, unrelated point in the flow -- right
    // after reading input, before deciding anything about it.
    #[cfg(target_os = "linux")]
    anti_debug::linux::check();
    #[cfg(target_os = "windows")]
    anti_debug::windows::check();

    let mut license_is_valid = check_license(provided_key);

    // Anti-debug check 3 of 3: timing anomaly again, at a third point --
    // immediately around the security-relevant decision itself, which is
    // exactly the kind of place F1.7 wants checks scattered near, not
    // centralized away from.
    anti_debug::timing::check();

    // F1.5, concretely implemented at the one call site in this crate that
    // actually knows what "the program's output" means: if tampering was
    // detected by *any* of the above (checksum mismatch or any anti-debug
    // check), silently flip a valid verdict to invalid. No error message
    // naming "tampering" is ever printed -- from the outside, a tampered
    // run that would otherwise have said "valid" just says "invalid",
    // indistinguishable from someone entering the wrong key.
    if tamper_detected() {
        license_is_valid = false;
    }

    if license_is_valid {
        println!("{}", valid_message());
    } else {
        println!("{}", invalid_message());
    }
}
